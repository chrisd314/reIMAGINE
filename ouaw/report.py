DIGITS = dict(zip("0123456789", ["Zero", "One", "Two", "Three", "Four", "Five", "Six", "Seven", "Eight", "Nine"]))


# ----------------------------------------------------------------- the number registry
def macro_name(parts) -> str:
    words = []
    for p in parts:
        for w in re.split(r"[^0-9A-Za-z]+", str(p)):
            if w:
                w = "".join(DIGITS.get(ch, ch) for ch in w)
                words.append(w[:1].upper() + w[1:])
    name = "".join(words)
    return name[:1].lower() + name[1:]


def tex_escape(s: str) -> str:
    s = s.replace("−", "-").replace("%", r"\%").replace("≥", r"$\geq$").replace("×", r"$\times$")
    s = re.sub(r"(?<=\d),(?=\d{3})", "{,}", s)
    return s.replace("< ", "$<$ ").replace("<", "$<$")


class Numbers:
    """Formats a number for the text and records it as a LaTeX macro; the same name must keep the same value."""

    def __init__(self):
        self.macros: dict[str, str] = {}

    def __call__(self, parts, value, kind: str = "f3") -> str:
        s = fmt(value, kind)
        key = macro_name(parts if isinstance(parts, (list, tuple)) else [parts])
        assert self.macros.get(key, s) == s, f"macro {key} registered twice with different values"
        self.macros[key] = s
        return s

    def tex(self, when: str) -> str:
        out = [f"% Generated by `python -m ouaw.run --stage figures` on {when}. Do not edit: rerun the pipeline.",
               "% Every number cited in report/RESULTS.md, report/captions.md and report/short_update.md."]
        out += [f"\\newcommand{{\\{k}}}{{{tex_escape(v)}}}" for k, v in sorted(self.macros.items())]
        return "\n".join(out) + "\n"


def fmt(x, kind: str) -> str:
    if isinstance(x, str):
        return x
    if x is None or (isinstance(x, float) and np.isnan(x)):
        return "n/a"
    if kind == "f2":
        return f"{x:.2f}"
    if kind == "f3":
        return f"{x:.3f}"
    if kind == "s3":
        return f"{x:+.3f}".replace("-", "−")
    if kind == "pct":
        return f"{100 * x:.0f}%"
    if kind == "pct1":
        return f"{100 * x:.1f}%"
    if kind == "pts":
        return f"{100 * x:+.0f}".replace("-", "−")
    if kind == "int":
        return f"{int(round(x)):,}"
    if kind == "p":
        return "< 0.001" if x < 0.001 else f"{x:.3f}"
    if kind == "z":
        return f"{x:.0f}"
    if kind == "f1":
        return f"{x:.1f}"
    raise ValueError(kind)


def pv(N: Numbers, parts, p) -> str:
    s = N(parts, p, "p")
    return f"p {s}" if s.startswith("<") else f"p = {s}"


def table(df: pd.DataFrame) -> list[str]:
    cols = list(df.columns)
    out = ["| " + " | ".join(cols) + " |", "| " + " | ".join("---" for _ in cols) + " |"]
    for _, r in df.iterrows():
        out.append("| " + " | ".join(str(r[c]) for c in cols) + " |")
    return out


def names(lst) -> str:
    lst = list(lst)
    if not lst:
        return "none"
    return lst[0] if len(lst) == 1 else ", ".join(lst[:-1]) + " and " + lst[-1]


def ordinal(s: str) -> str:
    n = int(s)
    return s + ("th" if 10 <= n % 100 <= 20 else {1: "st", 2: "nd", 3: "rd"}.get(n % 10, "th"))


def short_type(atu, name) -> str:
    return f"{atu} {str(name).split(' (previously')[0].split(' [')[0]}"


LEAN = 0.10          # a tradition "leans" toward a community when its parables' share exceeds the map share by 10 points


def shared_leans(cells: pd.DataFrame) -> list[dict]:
    """Communities that the parables of at least three traditions reach far beyond the community's share of the map,
    with how far the same traditions' baselines go beyond it."""
    x = cells.assign(par=cells["parable_share"] - cells["map_share"], base=cells["baseline_share"] - cells["map_share"])
    out = []
    for comm, g in x.groupby("community", sort=False):
        lean = g[g["par"] > LEAN]
        if len(lean) >= 3:
            out.append(dict(community=comm, words=", ".join(str(g["community_words"].iloc[0]).split()[:3]),
                            traditions=lean["tradition"].tolist(), par=float(lean["par"].mean()), base=float(lean["base"].mean())))
    return out


def lean_sentence(N: Numbers, rep: str, lean: dict) -> str:
    k = ["lean", rep, lean["community"]]
    shared = lean["base"] >= 0.75 * lean["par"]
    return (f"The parables of {names(lean['traditions'])} link to {lean['community']} ({lean['words']}) far beyond its share of the map "
            f"({N(k + ['parables'], lean['par'], 'pts')} points on average), "
            + (f"but so does their own baseline ({N(k + ['baseline'], lean['base'], 'pts')} points): this lean belongs to the translations, not to the parables."
               if shared else f"more than their own baseline does ({N(k + ['baseline'], lean['base'], 'pts')} points)."))


