def latex_text(x) -> str:
    """Escape LaTeX special characters in table text."""
    s = str(x)
    for ch, rep in (("\\", r"\textbackslash{}"), ("&", r"\&"), ("%", r"\%"), ("$", r"\$"), ("#", r"\#"), ("_", r"\_"),
                    ("{", r"\{"), ("}", r"\}"), ("~", r"\textasciitilde{}"), ("^", r"\textasciicircum{}")):
        s = s.replace(ch, rep)
    return s


def community_table_tex(ct: pd.DataFrame) -> str:
    """The community table of the map as a LaTeX tabular (its numbers come from results/community_table.csv)."""
    rows = [r"% Generated by the pipeline (results/community_table.csv). Do not edit.",
            r"\begin{tabular}{lrp{3.2cm}p{4.2cm}p{2.6cm}p{2.8cm}}", r"\hline",
            r"Community & Tales & Top words & Dominant tale types & Regions & Source collections \\", r"\hline"]
    for _, r in ct.iterrows():
        cells = [latex_text(r[c]) for c in ("community", "size", "top_words", "dominant_atu_types", "dominant_regions",
                                             "dominant_source_collections")]
        rows.append(" & ".join(cells) + r" \\")
    rows += [r"\hline", r"\end{tabular}"]
    return "\n".join(rows) + "\n"


def table1_tex(t1: pd.DataFrame) -> str:
    rows = [r"% Generated by the pipeline (results/table1_robustness.csv). Do not edit.",
            r"\begin{tabular}{p{2.6cm}p{4.2cm}lp{6.2cm}}", r"\hline",
            r"Check & What changes & Holds & Key number \\", r"\hline"]
    for _, r in t1.iterrows():
        rows.append(" & ".join(tex_escape(str(r[c])) for c in ("check", "variant", "holds", "key_number")) + r" \\")
    rows += [r"\hline", r"\end{tabular}"]
    return "\n".join(rows) + "\n"


